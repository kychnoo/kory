import kotlinx.serialization.Serializable
import kotlinx.serialization.json.JsonElement

/**
 * Raw OpenAI Responses API response.
 *
 * Contains the full response from the `/responses` endpoint: the generated
 * [output] items, token [usage], tool usage metering and request echo fields
 * (instructions, temperature, tools, etc.). Access the assistant's plain text
 * with [outputText], or inspect every generated item via [output].
 *
 * Example:
 * ```json
 * {
 *   "id": "resp_67ccd3a9da748190baa7f1570fe91ac6",
 *   "object": "response",
 *   "created_at": 1741476777,
 *   "completed_at": 1741476778,
 *   "status": "completed",
 *   "model": "gpt-5.6-sol",
 *   "output": [
 *     { "type": "message", "id": "msg_abc", "role": "assistant",
 *       "content": [{ "type": "output_text", "text": "Hi!" }], "status": "completed" }
 *   ],
 *   "usage": { "input_tokens": 10, "output_tokens": 7, "total_tokens": 17 },
 *   "incomplete_details": null,
 *   "error": null,
 *   "parallel_tool_calls": true,
 *   "temperature": 1.0,
 *   "tool_choice": "auto",
 *   "tools": [],
 *   "truncation": "disabled",
 *   "service_tier": "default"
 * }
 * ```
 *
 * @property id Unique identifier for this response.
 * @property obj Object type (always `"response"`).
 * @property createdAt Epoch timestamp when the response was created. `null` when not included.
 * @property completedAt Epoch timestamp when the response completed. `null` while the response is running.
 * @property status The lifecycle status of the response: `completed`, `failed`, `in_progress`,
 * `cancelled`, `queued` or `incomplete`. `null` when not included.
 * @property error The error, when the response [status][OpenAIResponseStatus] is `failed`.
 * `null` otherwise.
 * @property output The list of output items generated by the model (messages, tool calls, etc.).
 * @property incompleteDetails The reason the response is incomplete, when the
 * [status][OpenAIResponseStatus] is `incomplete`. `null` otherwise.
 * @property instructions The instructions (system prompt) the model used, as provided in the request.
 * `null` when not included.
 * @property model The model used for this response.
 * @property maxOutputTokens An upper bound for the number of tokens generated for this response.
 * `null` when not set.
 * @property maxToolCalls An upper bound for the number of tool calls generated for this response.
 * `null` when not set.
 * @property parallelToolCalls Whether the model was allowed to run tool calls in parallel.
 * `null` when not included.
 * @property previousResponseId The ID of the previous response in the same conversation chain.
 * `null` when not included.
 * @property reasoning The reasoning configuration the model used. `null` when not included.
 * @property store Whether the response was stored in the provider's storage. `null` when not included.
 * @property temperature The sampling temperature used. `null` when not included.
 * @property topP The nucleus sampling `top_p` value used. `null` when not included.
 * @property truncation The truncation strategy used for the response. `null` when not included.
 * @property text Configuration for the text output (format, verbosity). `null` when not included.
 * @property toolChoice How the model was allowed to choose tools. `null` when not included.
 * @property tools The tools available to the model for this response. `null` when not included.
 * @property usage Token usage statistics. `null` when not included (e.g. streaming events).
 * @property toolUsage Token usage per hosted tool, when the response was metered per tool.
 * `null` when not included.
 * @property serviceTier The processing tier actually used to serve the request.
 * `null` when not included.
 * @property metadata Metadata attached to the response. `null` when not included.
 * @property background Whether the response was created as a background job. `null` when not included.
 * @property user A stable identifier for the end user. `null` when not included.
 * @property safetyIdentifier A stable identifier used for safety/abuse tracking.
 * `null` when not included.
 * @property promptCacheKey A cache key used to route the request for prompt caching.
 * `null` when not included.
 *
 * @sample io.kory.openai.samples.response.processOpenAIResponsesResponse
 */
@Serializable
data class OpenAIResponsesResponse(
    val id: String,
    @SerialName("object") val obj: String = "response",
    @SerialName("created_at") val createdAt: Long? = null,
    @SerialName("completed_at") val completedAt: Long? = null,
    val status: OpenAIResponseStatus? = null,
    val error: OpenAIResponseError? = null,
    val output: List<OpenAIResponseOutputItem>,
    @SerialName("incomplete_details") val incompleteDetails: OpenAIIncompleteDetails? = null,
    val instructions: String? = null,
    val model: String? = null,
    @SerialName("max_output_tokens") val maxOutputTokens: Int? = null,
    @SerialName("max_tool_calls") val maxToolCalls: Int? = null,
    @SerialName("parallel_tool_calls") val parallelToolCalls: Boolean? = null,
    @SerialName("previous_response_id") val previousResponseId: String? = null,
    val reasoning: OpenAIReasoning? = null,
    val store: Boolean? = null,
    val temperature: Double? = null,
    @SerialName("top_p") val topP: Double? = null,
    val truncation: OpenAITruncation? = null,
    val text: OpenAIResponsesText? = null,
    @SerialName("tool_choice") val toolChoice: OpenAIToolChoice? = null,
    val tools: List<JsonElement> = emptyList(),
    val usage: OpenAIResponsesUsage? = null,
    @SerialName("tool_usage") val toolUsage: OpenAIResponsesToolUsage? = null,
    @SerialName("service_tier") val serviceTier: OpenAIServiceTier? = null,
    val metadata: OpenAIMetadata? = null,
    val background: Boolean? = null,
    val user: String? = null,
    @SerialName("safety_identifier") val safetyIdentifier: String? = null,
    @SerialName("prompt_cache_key") val promptCacheKey: String? = null,
) {
    val printableOutput: String = output.joinToString(separator = "\n") { it.printableContent }

    val outputText: String = output
        .filterIsInstance<OpenAIResponsesOutputMessage>()
        .flatMap { it.content }
        .filterIsInstance<OpenAIResponseOutputContent.ResponseOutputText>()
        .joinToString(separator = "") { it.text }
}
